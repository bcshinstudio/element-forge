const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context={window:{}};vm.createContext(context);vm.runInContext(fs.readFileSync(__dirname+'/../engine.js','utf8'),context);
const E=context.window.EFEngine;
const map=(w=5,h=5)=>({width:w,height:h,cells:Array.from({length:w*h},()=>({terrain:'land'}))});
const node=(m,i,element,role)=>m.cells[i].node={element,role};
let m=map();node(m,0,'fire','source');node(m,4,'fire','destination');
assert.equal(E.validatePath(m,'fire',[0,1,2,3,4]),null);
assert.ok(E.validatePath(m,'fire',[0,2,4]));
m.cells[2].terrain='water';assert.ok(E.validatePath(m,'fire',[0,1,2,3,4]));m.cells[2].component='bridge';assert.equal(E.validatePath(m,'fire',[0,1,2,3,4]),null);
let result=E.solveFixed(m);assert.equal(result.status,'solved');assert.equal(E.checkAll(m,result.routes).length,0);
let blocked=map();node(blocked,0,'fire','source');node(blocked,4,'fire','destination');for(let i=5;i<10;i++)blocked.cells[i].terrain='wall';assert.equal(E.solveFixed(blocked).status,'solved');
let cross=map();node(cross,10,'fire','source');node(cross,14,'fire','destination');node(cross,2,'water','source');node(cross,22,'water','destination');cross.cells[12].component='intersection';
assert.equal(E.validatePath(cross,'water',[2,7,12,17,22],[{element:'fire',path:[10,11,12,13,14]}]),null);
assert.ok(E.validatePath(cross,'water',[2,7,12,13,14],[{element:'fire',path:[10,11,12,13,14]}]));
console.log('PASS: engine path, terrain, bridge, intersection, fixed solver checks');
